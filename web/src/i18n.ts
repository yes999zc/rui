/** Locale-aware `H:MM:SS`, used by the signal ledger. */
export function formatUptime(seconds: number): string {
  if (!Number.isFinite(seconds) || seconds < 0) return '—'
  const total = Math.floor(seconds)
  const h = Math.floor(total / 3600)
  const m = Math.floor((total % 3600) / 60)
  const s = total % 60
  const pad = (n: number) => String(n).padStart(2, '0')
  return h > 0 ? `${h}:${pad(m)}:${pad(s)}` : `${pad(m)}:${pad(s)}`
}

/** Small numbers stay legible with thousands separators. */
export function formatCount(value: unknown): string {
  if (value == null || value === '') return '—'
  const n = Number(value)
  return Number.isFinite(n) ? n.toLocaleString(locale.value === 'zh' ? 'zh-CN' : 'en-US') : String(value)
}

/** A clock for "saved at" pills. */
export function formatClock(date = new Date()): string {
  return date.toLocaleTimeString(locale.value === 'zh' ? 'zh-CN' : 'en-GB', { hour12: false })
}


