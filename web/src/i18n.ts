const DICTS: Record<Locale, Record<MsgKey, string>> = { zh, en }

function detect(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'zh' || saved === 'en') return saved
  } catch {
    /* private mode */
  }
  const nav = typeof navigator === 'undefined' ? '' : navigator.language.toLowerCase()
  return nav.startsWith('zh') ? 'zh' : 'en'
}

export const locale = ref<Locale>(detect())

export function setLocale(next: Locale): void {
  locale.value = next
  try {
    localStorage.setItem(STORAGE_KEY, next)
  } catch {
    /* private mode */
  }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = next === 'zh' ? 'zh-Hans' : 'en'
  }
}

export function initLocale(): void {
  setLocale(locale.value)
}

export const isEnglish = computed(() => locale.value === 'en')

export function t(key: MsgKey, params?: Record<string, string | number>): string {
  let text = DICTS[locale.value][key] ?? DICTS.zh[key] ?? key
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

/** Pick `{zh,en}` catalog copy by the active locale; plain strings pass through. */
export function pickLocalized(value: unknown): string {
  if (value == null) return ''
  if (typeof value === 'string') return localizeBackend(value)
  if (typeof value === 'object') {
    const pair = value as { zh?: unknown; en?: unknown }
    const chosen = locale.value === 'en' ? pair.en ?? pair.zh : pair.zh ?? pair.en
    return chosen == null ? '' : String(chosen)
  }
  return String(value)
}

