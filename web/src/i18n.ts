/**
 * Translate backend-owned copy in either direction.
 *
 * The backend still sends natural-language labels inside PanelSpecs, plus a few
 * English enums (`ok`, `info`) as raw values. The bridge maps known strings
 * through the dictionary, so Chinese mode turns `ok` into 正常 and English mode
 * turns 服务 into Service. Unknown text falls through unchanged (a visible
 * contract gap, never a silent lie).
 */
export function localizeBackend(text: string | null | undefined): string {
  if (text == null) return ''
  const raw = String(text)
  const exact = BACKEND_KEYS[raw]
  if (exact) return t(exact)
  for (const rule of PATTERNS) {
    const match = raw.match(rule.re)
    if (match) return t(rule.key, rule.args?.(match))
  }
  // "3 次" / "12 首" style list subtitles: format() already resolved the number.
  const counted = raw.match(/^(\d+) (首|次|字|轮|秒)$/)
  if (counted) {
    const unit: Record<string, MsgKey> = {
      首: 'backend.unit.tracks',
      次: 'backend.unit.plays',
      字: 'backend.unit.chars',
      轮: 'backend.unit.rounds',
      秒: 'backend.unit.seconds',
    }
    return `${counted[1]} ${t(unit[counted[2]])}`
  }
  return raw
}

/**
 * FastAPI/pydantic 422 messages are English sentences (`must be less than or
 * equal to 300`). The field carries the backend's words; translate the common
 * forms so a Chinese operator reads the boundary, not the framework.
 */
export function localizeIssue(message: string | null | undefined): string {
  const raw = String(message ?? '')
  const max = raw.match(/less than or equal to\s+(-?[\d.]+)/i)
  if (max) return t('validation.max', { max: max[1] })
  const min = raw.match(/greater than or equal to\s+(-?[\d.]+)/i)
  if (min) return t('validation.min', { min: min[1] })
  if (/valid integer|valid float|valid number/i.test(raw)) return t('validation.number')
  if (/valid boolean/i.test(raw)) return t('validation.bool')
  if (/field required|missing/i.test(raw)) return t('validation.required')
  return raw
}

