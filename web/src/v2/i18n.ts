/** Prefer the translated stable code; fall back to the backend's English message. */
export function statusReasonText(
  reason: { code?: string; message?: string; hint?: string } | null | undefined,
): string {
  if (!reason) return ''
  const key = reason.code ? REASON_KEYS[reason.code] : undefined
  if (key) return t(key)
  return reason.hint || reason.message || t('v2.reason.other', { code: reason.code ?? '' })
}

